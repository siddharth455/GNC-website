<h2 id="lateral-entry">Can You Upgrade from D.Pharma to B.Pharma?</h2>

<p>Yes. Guru Nanak College offers Lateral Entry in B.Pharma for D.Pharma diploma holders, allowing direct admission into the second year of the B.Pharma program — saving time and tuition costs.</p>


