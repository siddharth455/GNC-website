<h2 id="post-basic-upgrade">Can GNM Students Upgrade to B.Sc Nursing?</h2>

<p>Yes. Guru Nanak College offers Post Basic B.Sc. Nursing — a bridge program specifically designed for GNM diploma holders to earn a bachelor's degree in nursing without repeating the full 4-year course.</p>


<h2 id="international-opportunities">International Career Opportunities</h2>

<p>Both B.Sc Nursing and GNM graduates from Guru Nanak College have growing opportunities for international placements, with hospitals in Gulf countries, UK, Germany, and Australia actively recruiting trained Indian nurses.</p>


<h2 id="why-study-at-gnc">Why Choose Guru Nanak College for Nursing?</h2>

<p>GNC's School of Nursing is INC-approved, offers hands-on clinical training through hospital tie-ups, and has a dedicated placement cell connecting students to top hospital recruiters.</p>

