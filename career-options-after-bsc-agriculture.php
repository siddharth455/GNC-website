<h2 id="government-jobs">Government Sector Jobs</h2>

<p>Agriculture graduates are eligible for roles in Agriculture Department services, ICAR research institutes, FCI, NABARD, and state agriculture extension services — many of which offer stable government salaries and job security.</p>


<h2 id="agribusiness">Agribusiness &amp; Private Sector</h2>

<p>Companies like ITC Agri, Bayer Crop Science, UPL, and seed/fertilizer companies actively hire B.Sc Agriculture graduates for roles in sales, agronomy, and field operations.</p>


<h2 id="higher-studies">Higher Studies — M.Sc Agriculture</h2>

<p>Graduates can pursue M.Sc Agriculture specializations like Agronomy, Plant Pathology, Horticulture, and Genetics &amp; Plant Breeding — both available at Guru Nanak College — to move into research, teaching, or specialized technical roles.</p>


<h2 id="agri-tech">Agri-Tech &amp; Entrepreneurship</h2>

<p>With India's growing agri-tech sector, graduates are increasingly starting their own ventures in organic farming, precision agriculture, and agri-startups, supported by government schemes for young agripreneurs.</p>


<h2 id="why-study-at-gnc">Why Choose Guru Nanak College for Agriculture?</h2>

<p>Guru Nanak College's School of Agriculture Science offers B.Sc Agriculture and B.Sc Forestry at the undergraduate level, with M.Sc Agronomy and M.Sc Horticulture for postgraduate specialization, supported by placement assistance across government and private sectors.</p>

